"""One semantic identity and final-result resolver for viewers and project bundles.

Project revision timestamps describe editor concurrency, not media contents. This
module deliberately ignores names, delivery folders and annotations generated by
alignment. It performs no decoding, model loading or credential access.
"""
from __future__ import annotations

import copy
import hashlib
import json
from pathlib import Path
import re

VERSION = 'npk-render-content-v1'
ID = re.compile(r'[0-9a-f]{32}')
MAX_INPUT_BYTES = 32 * 1024**2


def _digest(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                    separators=(',', ':'), allow_nan=False).encode()).hexdigest()


def _file_identity(value):
    if not value:
        return None
    path = Path(value)
    try:
        stat = path.stat()
        return [str(path.resolve()), stat.st_size, stat.st_mtime_ns]
    except OSError:
        return [str(path), 'missing']


def render_fingerprint(project):
    """Identity of requested picture/audio, independent of workflow provenance."""
    from core import restored_params, signature
    from subtitle_quality import source_signature
    p = restored_params(project.get('params', {}))
    effective = project | {'params': p}
    picture = {'burn_subtitles': bool(p.get('burn_subtitles')),
               'use_clean': bool(p.get('use_clean')),
               'export_resolution': p.get('export_resolution'),
               'video_quality': p.get('video_quality'), 'video_encoder': p.get('video_encoder')}
    captions = None
    if picture['burn_subtitles']:
        from core import SUBTITLE_STYLE_KEYS
        keys = SUBTITLE_STYLE_KEYS | {'subtitle_preset', 'subtitle_karaoke'}
        picture['caption_style'] = {key: p.get(key) for key in sorted(keys)}
        captions = [[r.get('start'), r.get('end'),
                     str(r.get('translated') or r.get('text') or '').strip(),
                     {key: value for key, value in (r.get('subtitle_style') or {}).items() if key in keys}]
                    for r in project.get('segments', [])]
    clean = signature(effective) if picture['use_clean'] else None
    voice_gain = float(p.get('voice_gain', 0))
    audio = {'original_gain': p.get('original_gain'), 'voice_gain': voice_gain,
             'voice_offset': p.get('voice_offset'), 'voice_normalize': p.get('voice_normalize'),
             'bgm_ducking': p.get('bgm_ducking'), 'bgm_gain': p.get('bgm_gain'),
             'bgm': _file_identity(p.get('bgm_path')) if float(p.get('bgm_gain', 0)) > 0 else None}
    if voice_gain > 0:
        if p.get('voice_path'):
            audio['voice'] = ['external', _file_identity(p['voice_path'])]
        else:
            # Inference-produced word timing is derived data. The same text,
            # voices and timing preferences remain current after it is attached.
            from worker import speech_signature
            audio['voice'] = ['synthesized', speech_signature(effective)]
    return _digest([VERSION, project.get('source_revision'), source_signature(project),
                    project['media'].get('width'), project['media'].get('height'),
                    picture, clean, captions, audio])


def admission_fingerprint(project, kind, segment_indices=None):
    """Semantic deduplication for a pending production run, never completed reuse."""
    p = project.get('params') or {}
    workflow = {key: p.get(key) for key in ('pipeline_extract', 'pipeline_translate', 'pipeline_tts',
        'pipeline_clean', 'provider', 'translation_model', 'target_language', 'source_language',
        'style', 'glossary', 'translation_scope', 'ocr_fps', 'ocr_confidence', 'ocr_similarity',
        'ocr_scale_mode', 'asr_model', 'asr_device', 'asr_compute', 'extraction_start', 'extraction_end', 'subtitle_automation')}
    if p.get('provider') == 'router9' or p.get('subtitle_automation') == 'router9':
        from providers import router_base_url
        workflow['router9_base_url'] = router_base_url(p.get('router9_base_url'))
    return _digest(['npk-admission-v1', kind, render_fingerprint(project),
                    project.get('extraction_regions'), project.get('segments', []),
                    workflow if kind in ('pipeline','auto_subtitles') else None,
                    sorted(set(segment_indices)) if segment_indices is not None else None])


def _final_anchor(row, data):
    """Read the identity captured when final.mp4 was successfully verified."""
    result = row.get('result') or {}
    verification = result.get('verification') or {}
    records = verification.get('file_integrity') if isinstance(verification, dict) else None
    if records is None:
        # Older pipeline results have a ledger written before final publication.
        # Its stored hashes can prove identity without decoding during polling.
        try:
            from stage_journal import load
            document = load(Path(data) / 'jobs' / row['id'])
            entry = document['stages'].get('render') or {}
            if (document.get('job_id') == row['id'] and
                    document.get('project_id') == row.get('project_id') and
                    document.get('source_revision') == row.get('source_revision') and
                    entry.get('result', {}).get('verification') and
                    (not result.get('render_fingerprint') or entry.get('signature') == result['render_fingerprint'])):
                records = entry.get('files')
        except (OSError, ValueError, KeyError, TypeError):
            pass
    if not isinstance(records, list):
        return None
    finals = [item for item in records if isinstance(item, dict) and item.get('name') == 'final.mp4']
    if len(finals) != 1:
        return None
    anchor = finals[0]
    if (set(anchor) != {'name', 'bytes', 'sha256'} or type(anchor['bytes']) is not int or anchor['bytes'] <= 0 or
            not isinstance(anchor['sha256'], str) or not re.fullmatch(r'[0-9a-f]{64}', anchor['sha256'])):
        return None
    return anchor


def final_result_status(row, data):
    """Resolve an unchanged local/published copy using cached content hashes.

    A missing legacy anchor means unknown, never a claim of corruption. A known
    mismatch cannot become a new identity. Prefer a valid local copy when the
    independently published copy has been changed or removed.
    """
    result = row.get('result') or {}
    identifier = str(row.get('id') or '')
    if (not ID.fullmatch(identifier) or row.get('state') != 'done' or
            result.get('primary_file') != 'final.mp4' or
            'final.mp4' not in result.get('files', []) or row.get('storage_removed')):
        raise ValueError('Tác vụ này chưa có video thành phẩm đã lưu. Video xử lý chữ không phải bản cuối.')
    anchor = _final_anchor(row, data)
    candidates = []
    published = result.get('published') or {}
    if published.get('path'):
        candidates.append(('published', Path(published['path'])))
    root = (Path(data)/'jobs').resolve()
    path = root/identifier/'final.mp4'
    if not path.is_symlink() and root in path.resolve().parents:
        candidates.append(('local', path))
    checked, available = [], []
    from stage_journal import describe_file
    for role, candidate in candidates:
        state = 'missing'
        try:
            if candidate.is_file() and not candidate.is_symlink():
                state = 'unknown'
                if anchor is not None:
                    actual = describe_file(candidate.parent, candidate.name)
                    state = ('verified' if (actual['bytes'], actual['sha256']) ==
                             (anchor['bytes'], anchor['sha256']) else 'corrupt')
                if state in ('verified', 'unknown'):
                    available.append((role, candidate.resolve(strict=True), state))
        except (OSError, ValueError, TypeError):
            state = 'unreadable'
        checked.append({'role': role, 'path': str(candidate), 'status': state})
    if available:
        role, selected, state = available[0]
        warning = ('Bản trong thư mục xuất đã thay đổi; đang dùng bản đã kiểm trong dự án.'
                   if role == 'local' and any(item['role'] == 'published' and item['status'] == 'corrupt' for item in checked) else '')
        return {'status': state, 'path': selected, 'copies': checked, 'warning': warning}
    return {'status': 'corrupt' if any(item['status'] == 'corrupt' for item in checked) else 'missing',
            'path': None, 'copies': checked, 'warning': ''}


def final_result_path(row, data):
    """Explicit legacy job links stay available, without certifying them current."""
    state = final_result_status(row, data)
    if state['status'] == 'corrupt':
        raise ValueError('Tệp video thành phẩm đã thay đổi so với lần kiểm chứng. Khôi phục bản đã kiểm hoặc xuất lại.')
    if state['path'] is None:
        raise ValueError('Video thành phẩm đã được dọn hoặc không còn tệp đọc được.')
    return state['path']


def _legacy_fingerprint(row, project, data):
    """Prove legacy contents from a bound snapshot; timestamps are not proof."""
    path = Path(data)/'jobs'/row['id']/'input.json'
    if path.is_symlink() or not path.is_file() or path.stat().st_size > MAX_INPUT_BYTES:
        return None
    try:
        with path.open('rb') as stream:
            encoded = stream.read(MAX_INPUT_BYTES + 1)
        if len(encoded) > MAX_INPUT_BYTES:
            return None
        document = json.loads(encoded.decode('utf-8'))
        saved, job = document['project'], document['job']
        if (saved.get('id') != row.get('project_id') or job.get('id') != row.get('id') or
                job.get('project_id') != row.get('project_id') or
                job.get('source_revision') != row.get('source_revision') or
                saved.get('source_revision') != project.get('source_revision')):
            return None
        saved = copy.deepcopy(saved)
        result = row.get('result') or {}
        from subtitle_quality import source_signature
        coverage = result.get('coverage') or saved.get('coverage') or {}
        if coverage.get('source_signature') != source_signature(project):
            # Legacy input media did not store mtime/hash. Reading the file's
            # *current* stat would otherwise certify a same-path replacement.
            return None
        if isinstance(result.get('segments'), list):
            saved['segments'] = result['segments']
        if isinstance(result.get('artifacts'), dict):
            saved.setdefault('artifacts', {}).update(result['artifacts'])
        return render_fingerprint(saved)
    except (OSError, ValueError, KeyError, TypeError, RecursionError):
        return None


def resolve_final(project, jobs, data):
    """Return newest current final and separately newest same-source history."""
    try:
        wanted = render_fingerprint(project)
    except (OSError, ValueError, KeyError, TypeError):
        wanted = None
    artifacts = {a['job_id']: a for a in (project.get('artifacts') or {}).values()
                 if isinstance(a, dict) and a.get('job_id') and a.get('primary_file') == 'final.mp4'}
    current, historical, unavailable = [], [], []
    for row in jobs:
        artifact = artifacts.get(row.get('id')) or {}
        if (row.get('project_id') != project['id'] and artifact.get('source_project_id') != row.get('project_id')):
            continue
        if row.get('source_revision') != project.get('source_revision'):
            continue
        try:
            payload = final_result_status(row, data)
        except (OSError, ValueError, TypeError):
            continue
        if payload['path'] is None:
            unavailable.append({'job_id': row['id'], 'status': payload['status'], 'copies': payload['copies']})
            continue
        path = payload['path']
        result = row.get('result') or {}
        fingerprint = result.get('render_fingerprint') or _legacy_fingerprint(row, project, data)
        verified = payload['status'] == 'verified'
        matches = wanted is not None and fingerprint == wanted and verified
        item = {'job_id': row['id'], 'kind': row.get('kind'), 'created': row.get('created', 0),
                'path': str(path), 'current': matches, 'render_fingerprint': fingerprint,
                'identity_verified': bool(fingerprint and verified), 'payload_status': payload['status'],
                'copies': payload['copies'], 'delivery_warning': payload['warning'],
                'artifact': artifact or {'job_id': row['id'], 'primary_file': 'final.mp4'},
                'reason': '' if matches else ('Bản xuất cũ chưa có dấu vết hash của lần kiểm chứng; cần kiểm lại tệp trước khi coi là thành phẩm hiện tại.'
                                             if not verified else 'Nội dung hoặc cấu hình đã thay đổi; đây là video của lượt trước.'
                                             if fingerprint else 'Bản xuất cũ chưa có bằng chứng khớp nội dung hiện tại.')}
        (current if matches else historical).append(item)
    latest = lambda rows: max(rows, key=lambda row: (row['created'], row['job_id']), default=None)
    return {'current': latest(current), 'historical': latest(historical),
            'requested_fingerprint': wanted, 'unavailable': unavailable}
